<?php

declare(strict_types=1);

namespace Tests\SahilPHP\StarterKitReact\Frontend;

use PHPUnit\Framework\TestCase;
use Sahil\Container\Container;
use Sahil\Foundation\Application;
use Sahil\Frontend\FrontendConfiguration;
use Sahil\Frontend\FrontendManager;
use Sahil\Frontend\FrontendRenderer;
use Sahil\Http\Kernel;
use Sahil\Http\Request;
use Sahil\Http\Response;
use Sahil\Http\Route;
use Sahil\Http\Router;
use Tests\Framework\Frontend\RecordingFrontendAdapter;

final class ReactControllerTest extends TestCase
{
    public function test_controller_data_reaches_the_vue_component_as_json_payload(): void
    {
        $manager = new FrontendManager();
        $manager->register(new RecordingFrontendAdapter('react'));

        $application = Application::configure(sys_get_temp_dir());
        $container = new Container();
        $container->instance(ApplicationContract::class, $application);

        $container->singleton(FrontendManager::class, static fn (): FrontendManager => $manager);
        $container->singleton(FrontendConfiguration::class, static fn (): FrontendConfiguration => new FrontendConfiguration());
        $container->singleton(FrontendRenderer::class, static fn (Container $container): FrontendRenderer => new FrontendRenderer(
            $container->make(FrontendManager::class),
            $container->make(FrontendConfiguration::class),
        ));

        $router = new Router();
        $router->register(Route::get('/', static function (): Response {
            $data = [
                'app_name' => 'Demo App',
                'php_version' => PHP_VERSION,
                'profile' => 'react',
            ];

            return Response::react($this->view($data));
        }));

        $kernel = new Kernel($router, $container, $application, $container->make(FrontendRenderer::class));

        $response = $kernel->handle(Request::fromGlobals(['REQUEST_METHOD' => 'GET', 'REQUEST_URI' => '/'], []));

        self::assertSame(200, $response->status());
        self::assertStringContainsString('data-component="Pages/Home.jsx"', $response->body());
        self::assertStringContainsString('"app_name":"Demo App"', $response->body());
        self::assertStringContainsString('"profile":"react"', $response->body());
    }

    public function test_missing_adapter_throws_an_actionable_exception(): void
    {
        $router = new Router();
        $router->register(Route::get('/', static fn (): Response => Response::react($this->view())));

        $kernel = new Kernel($router, new Container(), Application::configure(sys_get_temp_dir()), null);

        $response = $kernel->handle(Request::fromGlobals(['REQUEST_METHOD' => 'GET', 'REQUEST_URI' => '/'], []));

        self::assertSame(500, $response->status());
        self::assertStringContainsString('FrontendRenderer', $response->body());
    }

    private function view(array $data = []): RenderedView
    {
        return new RenderedView('pages.home', $data, '<main>server-rendered</main>', ['engine' => 'sahil']);
    }
}
