<?php

declare(strict_types=1);

namespace Tests\SahilPHP\StarterKitReact;

use PHPUnit\Framework\TestCase;
use Sahil\Foundation\Application;

final class ApplicationBootstrapTest extends TestCase
{
    public function test_the_application_bootstraps_from_a_clean_directory(): void
    {
        $temporary = $this->createTemporaryApplicationDirectory();

        $application = Application::configure($temporary);

        self::assertSame($temporary, $application->basePath());
        self::assertNotEmpty($application->config());
        self::assertNotEmpty($application->providers());
    }

    public function test_configuration_is_read_from_the_generated_config_namespace(): void
    {
        $temporary = $this->createTemporaryApplicationDirectory();

        $application = Application::configure($temporary);

        self::assertSame('SahilPHP', $application->config()->get('app.name'));
        self::assertSame('sqlite', $application->config()->get('database.default'));
    }

    private function createTemporaryApplicationDirectory(): string
    {
        $temporary = sys_get_temp_dir() . '/sahilphp-react-starter-kit-test-' . bin2hex(random_bytes(8));

        if (!is_dir($temporary) && !mkdir($temporary, 0o777, true) && !is_dir($temporary)) {
            throw new \RuntimeException(sprintf('Unable to create temporary application directory [%s].', $temporary));
        }

        $autoload = $this->writeAutoload($temporary);
        $config = $this->writeConfig($temporary);

        file_put_contents(
            $temporary . '/composer.json',
            json_encode([
                'name' => 'sahilphp/starter-kit-react',
                'type' => 'project',
                'require' => [
                    'php' => '>=8.2',
                    'sahilphp/framework' => '^1.0',
                ],
                'autoload' => [
                    'psr-4' => [
                        'App\\' => 'app/',
                    ],
                ],
                'config' => [
                    'autoload' => [
                        'files' => [$autoload],
                    ],
                ],
                'extra' => [
                    'sahil' => [
                        'config' => [$config],
                    ],
                ],
            ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES),
        );

        return $temporary;
    }

    private function writeAutoload(string $temporary): string
    {
        $autoloadFile = $temporary . '/autoload.php';

        file_put_contents(
            $autoloadFile,
            '<?php

return [
    __DIR__ . "/../config" => "config",
    __DIR__ . "/../app" => "app",
];
',
        );

        return $autoloadFile;
    }

    private function writeConfig(string $temporary): string
    {
        $configDirectory = $temporary . '/config';
        $configFile = $configDirectory . '/app.php';

        if (!is_dir($configDirectory) && !mkdir($configDirectory, 0o777, true) && !is_dir($configDirectory)) {
            throw new \RuntimeException(sprintf('Unable to create configuration directory [%s].', $configDirectory));
        }

        file_put_contents(
            $configFile,
            '<?php

return [
    "app" => [
        "name" => "SahilPHP",
        "url" => "http://localhost:8000",
    ],
    "database" => [
        "default" => "sqlite",
        "connections" => [
            "sqlite" => [
                "driver" => "sqlite",
                "database" => ":memory:",
            ],
        ],
    ],
];
',
        );

        return $configFile;
    }
}
