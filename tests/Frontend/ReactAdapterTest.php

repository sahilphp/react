<?php

declare(strict_types=1);

namespace Tests\SahilPHP\StarterKitReact\Frontend;

use PHPUnit\Framework\TestCase;
use Sahil\Frontend\FrontendAdapterContract;
use Sahil\Frontend\FrontendAssets;
use Sahil\Frontend\InvalidFrontendConfigurationException;
use Sahil\View\RenderedView;
use Tests\Framework\Frontend\RecordingFrontendAdapter;

final class ReactAdapterTest extends TestCase
{
    public function test_adjusts_the_vue_adapter_component_to_a_react_entry(): void
    {
        $adapter = new RecordingFrontendAdapter('react', 'Pages/Home.jsx');

        self::assertSame('react', $adapter->name());
        self::assertSame('Pages/Home.jsx', $adapter->component($this->view()));
        self::assertSame(['data-framework' => 'react'], $adapter->mountAttributes($this->view()));
        self::assertSame(
            new FrontendAssets(['http://127.0.0.1:5173/resources/js/app.js'], ['/build/assets/app.css']),
            $adapter->assets(true),
        );
    }

    public function test_payload_passes_controller_data_to_javascript(): void
    {
        $adapter = new RecordingFrontendAdapter('react');

        $view = new RenderedView('pages.dashboard', [
            'app_name' => 'Demo',
            'php_version' => PHP_VERSION,
            'markdown' => '<b>escaped</b>',
        ], '<main></main>');

        self::assertSame([
            'app_name' => 'Demo',
            'php_version' => PHP_VERSION,
            'markdown' => '<b>escaped</b>',
        ], $adapter->payload($view));
    }

    public function test_mount_attributes_are_escaped(): void
    {
        $adapter = new RecordingFrontendAdapter('react', attributes: ['data-api' => '"><script>alert(1)</script>']);

        self::assertSame(
            ['data-api' => '"><script>alert(1)</script>'],
            $adapter->mountAttributes($this->view()),
        );

        $this->expectException(InvalidFrontendConfigurationException::class);
        $this->expectExceptionMessage('Invalid mount attribute name');

        $adapter->mountAttributes($this->view());
    }

    public function test_event_handler_attributes_are_refused(): void
    {
        $adapter = new RecordingFrontendAdapter('react', attributes: ['onclick' => 'alert(1)']);

        $this->expectException(InvalidFrontendConfigurationException::class);
        $this->expectExceptionMessage('Event-handler attribute [onclick]');

        $adapter->mountAttributes($this->view());
    }

    public function test_assets_are_resolved_for_both_modes(): void
    {
        $adapter = new RecordingFrontendAdapter('react');

        $adapter->assets(true);
        $adapter->assets(false);

        self::assertSame([true, false], $adapter->assetModes);
    }

    private function view(array $data = []): RenderedView
    {
        return new RenderedView('pages.home', $data, '<main>server-rendered</main>', ['engine' => 'sahil']);
    }
}
