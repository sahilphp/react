import React from 'react';

export type AlertVariant = 'success' | 'warning' | 'danger';

export interface AlertProps {
    variant?: AlertVariant;
    title?: string;
    message?: string;
}

const variantStyles: Record<AlertVariant, string> = {
    success: 'alert--success',
    warning: 'alert--warning',
    danger: 'alert--danger',
};

export const Alert: React.FC<AlertProps> = ({
    variant = 'success',
    title = 'Notice',
    message,
}) => {
    return (
        <div className={`alert ${variantStyles[variant]}`} role="status">
            <div className="alert__icon">
                {variant === 'success' && (
                    <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true" focusable="false">
                        <circle cx="12" cy="12" r="11" fill="none" stroke="#166534" strokeWidth="2" />
                        <path d="M8 12.5 L11 15.5 L16 9" fill="none" stroke="#166534" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
                    </svg>
                )}
                {variant === 'warning' && (
                    <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true" focusable="false">
                        <circle cx="12" cy="12" r="11" fill="none" stroke="#b45309" strokeWidth="2" />
                        <path d="M12 8v4" stroke="#b45309" strokeWidth="2" strokeLinecap="round" />
                        <circle cx="12" cy="16" r="0.8" fill="#b45309" />
                    </svg>
                )}
                {variant === 'danger' && (
                    <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true" focusable="false">
                        <circle cx="12" cy="12" r="11" fill="none" stroke="#991b1b" strokeWidth="2" />
                        <path d="M12 8v8" stroke="#991b1b" strokeWidth="2" strokeLinecap="round" />
                        <path d="M12 16h.01" stroke="#991b1b" strokeWidth="2" strokeLinecap="round" />
                    </svg>
                )}
            </div>
            <div className="alert__body">
                <p className="alert__title">{title}</p>
                {message && <p className="alert__message">{message}</p>}
            </div>
        </div>
    );
};
