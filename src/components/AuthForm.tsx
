import React, { useState } from 'react';
import { FormField } from '@/components/FormField';

export type AuthMode = 'login' | 'register' | 'forgot';

export interface AuthResult {
    message?: string;
}

export interface AuthFormProps {
    mode: AuthMode;
    submitLabel: string;
    result?: AuthResult;
    onSubmit: () => void;
}

export const AuthForm: React.FC<AuthFormProps> = ({
    mode,
    submitLabel,
    result,
    onSubmit,
}) => {
    const [email, setEmail] = useState('');
    const [password, setPassword] = useState('');
    const [confirmPassword, setConfirmPassword] = useState('');

    const showEmail = mode === 'register' || mode === 'forgot';
    const showPassword = mode === 'login' || mode === 'register';
    const showConfirmPassword = mode === 'register';

    const [errors, setErrors] = useState<Record<string, string>>({});

    const validate = (): Record<string, string> => {
        const next: Record<string, string> = {};
        if (showEmail && !email.trim()) next.email = 'Email is required.';
        if (showPassword && !password) next.password = 'Password is required.';
        if (showConfirmPassword && confirmPassword !== password) {
            next.confirmPassword = 'Passwords must match.';
        }
        return next;
    };

    const submit = (event: React.FormEvent) => {
        event.preventDefault();
        const validationErrors = validate();
        setErrors(validationErrors);
        if (Object.keys(validationErrors).length > 0) {
            return;
        }
        onSubmit();
    };

    return (
        <div className="auth-form__card">
            <form noValidate onSubmit={submit}>
                {showEmail && (
                    <div className="auth-form__field">
                        <label className="auth-form__label" htmlFor="auth-email">
                            Email
                        </label>
                        <input
                            id="auth-email"
                            name="email"
                            type="email"
                            autoComplete="email"
                            value={email}
                            onChange={(event) => setEmail(event.target.value)}
                            placeholder="you@example.com"
                        />
                        {errors.email && (
                            <p className="auth-form__error" role="alert">
                                {errors.email}
                            </p>
                        )}
                    </div>
                )}

                {showPassword && (
                    <div className="auth-form__field">
                        <label className="auth-form__label" htmlFor="auth-password">
                            Password
                        </label>
                        <input
                            id="auth-password"
                            name="password"
                            type="password"
                            autoComplete="current-password"
                            value={password}
                            onChange={(event) => setPassword(event.target.value)}
                            placeholder="Enter your password"
                        />
                        {errors.password && (
                            <p className="auth-form__error" role="alert">
                                {errors.password}
                            </p>
                        )}
                    </div>
                )}

                {showConfirmPassword && (
                    <div className="auth-form__field">
                        <label className="auth-form__label" htmlFor="auth-confirm-password">
                            Confirm password
                        </label>
                        <input
                            id="auth-confirm-password"
                            name="password_confirmation"
                            type="password"
                            autoComplete="new-password"
                            value={confirmPassword}
                            onChange={(event) => setConfirmPassword(event.target.value)}
                            placeholder="Repeat your password"
                        />
                        {errors.confirmPassword && (
                            <p className="auth-form__error" role="alert">
                                {errors.confirmPassword}
                            </p>
                        )}
                    </div>
                )}

                <button type="submit" className="btn btn--primary">
                    {submitLabel}
                </button>

                {result?.message && (
                    <p className="auth-form__message" role="status">
                        {result.message}
                    </p>
                )}
            </form>
        </div>
    );
};
