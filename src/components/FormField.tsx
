import React, { InputHTMLAttributes, LabelHTMLAttributes } from 'react';

export interface FormFieldProps extends Omit<InputHTMLAttributes<HTMLInputElement>, 'name' | 'onChange'> {
    name: string;
    label: string;
    value?: string;
    onChange?: (value: string) => void;
    errors?: Record<string, string>;
    rows?: number;
}

export const FormField: React.FC<FormFieldProps> = ({
    name,
    label,
    type = 'text',
    value,
    onChange,
    errors,
    rows,
    ...inputProps
}) => {
    const hasError = Boolean(errors?.[name]);

    return (
        <div className={`form__field${hasError ? ' form__field--error' : ''}`}>
            <label className="form__label" htmlFor={`field-${name}`}>
                {label}
            </label>
            {type === 'textarea' ? (
                <textarea
                    className="form__input"
                    id={`field-${name}`}
                    name={name}
                    rows={rows ?? 4}
                    value={value ?? ''}
                    {...inputProps}
                />
            ) : (
                <input
                    className="form__input"
                    id={`field-${name}`}
                    name={name}
                    type={type}
                    value={value ?? ''}
                    onChange={(event) => onChange?.(event.currentTarget.value)}
                    {...inputProps}
                />
            )}
            {hasError && (
                <p className="form__error" role="alert">
                    {errors[name] ?? 'This field is invalid.'}
                </p>
            )}
        </div>
    );
};
